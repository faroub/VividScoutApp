// ---------------------------------------------------------------------------
// shared_trips — Cloud-Function-mediated creation
//
// firestore.rules denies ALL direct client writes: the rules language cannot
// validate list contents (no iteration; the CEL all() macro is unsupported and
// the 1000-expression cap forbids bounded explicit per-entry validation of 50
// waypoints — verified empirically against the rules engine). Shared trips are
// created only by the trusted publishSharedTrip Cloud Function, which validates
// the full payload server-side (see functions/sharedTrips.test.js) and writes
// via the Admin SDK. Documents here are seeded exactly like that trusted
// writer (Admin SDK against the same emulator), and the rules layer is then
// exercised for public exact-ID reads, expiry, and immutability.
// ---------------------------------------------------------------------------

describe("shared_trips", () => {
  const validTripPayload = (id) => ({
    id,
    title: "Alfama Sunrise Walk",
    spots: [
      {
        spotId: "spot-1",
        title: "Miradouro de Santa Luzia",
        category: "viewpoints",
        latitude: 38.7133,
        longitude: -9.1278,
        imageUrl: "https://storage.googleapis.com/vividscout/spot.jpg",
      },
      {
        spotId: "spot-2",
        title: "Castelo de São Jorge",
        category: "sights",
        latitude: 38.7142,
        longitude: -9.1305,
        imageUrl: "",
      },
    ],
    createdAt: Date.now(),
    expireAt: Date.now() + 30 * 24 * 3600 * 1000,
  });

  // Writes like the trusted Cloud Function: Admin SDK (bypasses rules) with
  // real Firestore Timestamps, exactly the document the function persists.
  const seedTripAsTrustedWriter = async (data) => {
    const adminDb = admin.firestore();
    const ts = (millis) => admin.firestore.Timestamp.fromMillis(millis);
    await adminDb
      .collection("shared_trips")
      .doc(data.id)
      .set({
        ...data,
        createdAt: ts(data.createdAt),
        expireAt: ts(data.expireAt),
      });
  };

  it("denies direct authenticated client creation of shared trips", async () => {
    const id = nextId("trip");
    await assertFails(setDoc(doc(dbAs(ALICE), "shared_trips", id), validTripPayload(id)));
  });

  it("denies unauthenticated client creation of shared trips", async () => {
    const id = nextId("trip");
    await assertFails(setDoc(doc(dbAs(null), "shared_trips", id), validTripPayload(id)));
  });

  it("allows the public to read an unexpired trip by exact document ID", async () => {
    const id = nextId("trip");
    await seedTripAsTrustedWriter(validTripPayload(id));
    const saved = await getDoc(doc(dbAs(null), "shared_trips", id));
    assert.strictEqual(saved.get("id"), id);
    assert.strictEqual(saved.get("spots").length, 2);
  });

  it("rejects public reads once the trip has expired", async () => {
    const id = nextId("trip");
    const data = validTripPayload(id);
    data.expireAt = Date.now() - 60 * 1000;
    await seedTripAsTrustedWriter(data);
    await assertFails(getDoc(doc(dbAs(null), "shared_trips", id)));
  });

  it("rejects reads when expireAt is not a Firestore Timestamp", async () => {
    const id = nextId("trip");
    const data = validTripPayload(id);
    await seedTripAsTrustedWriter(data);
    // Overwrite with a raw number expireAt through the Admin SDK (only the
    // trusted writer could have produced such a document pre-enforcement).
    await admin.firestore().collection("shared_trips").doc(id).update({ expireAt: data.expireAt });
    await assertFails(getDoc(doc(dbAs(null), "shared_trips", id)));
  });

  it("rejects list and query access while allowing exact-id reads", async () => {
    const id = nextId("trip");
    await seedTripAsTrustedWriter(validTripPayload(id));
    const reader = dbAs(null);
    await assertFails(getDocs(collection(reader, "shared_trips")));
    await assertFails(
      getDocs(query(collection(reader, "shared_trips"), where("id", "==", id)))
    );
    await assertSucceeds(getDoc(doc(reader, "shared_trips", id)));
  });

  it("rejects updates to a published shared trip", async () => {
    const id = nextId("trip");
    await seedTripAsTrustedWriter(validTripPayload(id));
    await assertFails(updateDoc(doc(dbAs(ALICE), "shared_trips", id), { title: "Renamed Walk" }));
  });

  it("rejects deletion of a published shared trip", async () => {
    const id = nextId("trip");
    await seedTripAsTrustedWriter(validTripPayload(id));
    await assertFails(deleteDoc(doc(dbAs(ALICE), "shared_trips", id)));
  });
});

