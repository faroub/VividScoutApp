describe('storage spot_photos', () => {
  const JPEG = Buffer.from([0xff, 0xd8, 0xff, 0xe0, 0x00, 0x10, 0x4a, 0x46, 0x49, 0x46]);

  it('allows public reads of stored photos', async () => {
    const objectPath = `spot_photos/${ALICE}/spot-1/${nextId('photo')}.jpg`;
    const ownerStorage = storageAs(ALICE);
    await assertSucceeds(
      uploadBytes(ref(ownerStorage, objectPath), JPEG, { contentType: 'image/jpeg' })
    );
    await assertSucceeds(getDownloadURL(ref(storageAs(null), objectPath)));
  });

  it('allows the path owner to upload a JPEG under 5 MB', async () => {
    const objectPath = `spot_photos/${ALICE}/spot-1/${nextId('photo')}.jpg`;
    await assertSucceeds(
      uploadBytes(ref(storageAs(ALICE), objectPath), JPEG, { contentType: 'image/jpeg' })
    );
  });

  it('rejects unauthenticated uploads', async () => {
    const objectPath = `spot_photos/${ALICE}/spot-1/${nextId('photo')}.jpg`;
    await assertFails(
      uploadBytes(ref(storageAs(null), objectPath), JPEG, { contentType: 'image/jpeg' })
    );
  });

  it('rejects uploads to another user ownership path', async () => {
    const objectPath = `spot_photos/${ALICE}/spot-1/${nextId('photo')}.jpg`;
    await assertFails(
      uploadBytes(ref(storageAs(BOB), objectPath), JPEG, { contentType: 'image/jpeg' })
    );
  });

  it('rejects uploads with a non-image content type', async () => {
    const objectPath = `spot_photos/${ALICE}/spot-1/${nextId('photo')}.jpg`;
    await assertFails(
      uploadBytes(ref(storageAs(ALICE), objectPath), JPEG, { contentType: 'application/pdf' })
    );
  });

  it('rejects uploads larger than 5 MB', async () => {
    const objectPath = `spot_photos/${ALICE}/spot-1/${nextId('photo')}.jpg`;
    const oversized = Buffer.alloc(5 * 1024 * 1024 + 1, 0);
    await assertFails(
      uploadBytes(ref(storageAs(ALICE), objectPath), oversized, { contentType: 'image/jpeg' })
    );
  });

  it('allows the path owner to delete their upload, rejects deletion by others', async () => {
    const objectPath = `spot_photos/${ALICE}/spot-1/${nextId('photo')}.jpg`;
    const ownerStorage = storageAs(ALICE);
    await assertSucceeds(
      uploadBytes(ref(ownerStorage, objectPath), JPEG, { contentType: 'image/jpeg' })
    );
    await assertFails(deleteObject(ref(storageAs(BOB), objectPath)));
    await assertSucceeds(deleteObject(ref(ownerStorage, objectPath)));
  });

  it('rejects overwriting another user object (update by non-owner)', async () => {
    const objectPath = `spot_photos/${ALICE}/spot-1/${nextId('photo')}.jpg`;
    const ownerStorage = storageAs(ALICE);
    await assertSucceeds(
      uploadBytes(ref(ownerStorage, objectPath), JPEG, { contentType: 'image/jpeg' })
    );
    await assertFails(
      uploadBytes(ref(storageAs(BOB), objectPath), JPEG, { contentType: 'image/jpeg' })
    );
  });
});

