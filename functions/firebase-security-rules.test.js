// ---------------------------------------------------------------------------
// Atomic transaction helpers. These mirror the exact production shapes:
// FirestoreSyncManager.upvoteTipInCloud (community_tips/votes) and
// PhotoModerationRepository.reportPhoto (spot_photos/reports). The parent
// counter is written as the transaction-read value + 1 (no FieldValue.increment)
// so the Firestore rules child-create checks can observe the before/after
// counter state within the transaction.
// ---------------------------------------------------------------------------

const atomicVote = async (db, tipId, uid) => {
  const tipRef = doc(db, 'community_tips', tipId);
  const voteRef = doc(db, 'community_tips', tipId, 'votes', uid);
  await runTransaction(db, async (txn) => {
    const tipDoc = await txn.get(tipRef);
    const count = tipDoc.get('upvotes') ?? 0;
    txn.update(tipRef, { upvotes: count + 1 });
    txn.set(voteRef, { uid, timestamp: Date.now() });
  });
};

const atomicReport = async (db, photoId, uid) => {
  const photoRef = doc(db, 'spot_photos', photoId);
  const reportRef = doc(db, 'spot_photos', photoId, 'reports', uid);
  await runTransaction(db, async (txn) => {
    const photoDoc = await txn.get(photoRef);
    const count = photoDoc.get('reportsCount') ?? 0;
    txn.update(photoRef, { reportsCount: count + 1 });
    txn.set(reportRef, { reporterUid: uid, timestamp: Date.now() });
  });
};

